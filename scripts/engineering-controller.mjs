import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
const repo=process.env.GITHUB_REPOSITORY;
if(repo!=='duykhang68/khoahoctienghan')throw Error('Wrong repository');
const event=JSON.parse(readFileSync(process.env.GITHUB_EVENT_PATH,'utf8'));
const cli=(args,input)=>execFileSync('gh',args,{encoding:'utf8',input,stdio:['pipe','pipe','pipe'],maxBuffer:16*1024*1024});
const api=(path,method='GET',data)=>{const out=cli(['api','-X',method,'repos/'+repo+'/'+path,...(data?['--input','-']:[])],data?JSON.stringify(data):undefined);return out?JSON.parse(out):null};
const all=(path)=>JSON.parse(cli(['api','--paginate','--slurp','repos/'+repo+'/'+path])).flat();
const issues=all('issues?state=all&per_page=100').filter(i=>!i.pull_request);
const main=api('git/ref/heads/main').object.sha;
const ciName='P0 · Knowledge Base CI';
const ciPath='ci.yml';
const hasMarker=(i,m)=>String(i.body||'').includes(m);
function incident(key,title,body){
 const marker='<!-- engine-id:'+key+' -->';
 if(issues.some(i=>hasMarker(i,marker)))return;
 const i=api('issues','POST',{title,body:'<!-- engineering-incident:v1 -->\n'+marker+'\nStatus: investigating\n\n'+body});
 issues.push(i);
 console.log('Incident #'+i.number);
}
const runs=api('actions/workflows/'+ciPath+'/runs?per_page=100').workflow_runs;
const prs=all('pulls?state=open&base=main&per_page=100').sort((a,b)=>a.number-b.number);
const trusted=p=>p.user.login==='duykhang68'&&p.head.repo?.full_name===repo&&!p.draft&&/^(p\d+[/-]|fix\/|feat\/|ui\/|ux\/|docs\/|techblog\/)/.test(p.head.ref);
const sensitive=p=>all('pulls/'+p.number+'/files?per_page=100').some(f=>/^(\.github\/|AGENTS\.md$|engineering\/|scripts\/|package(?:-lock)?\.json$)/.test(f.filename)||/^(\.github\/|AGENTS\.md$|engineering\/|scripts\/|package(?:-lock)?\.json$)/.test(f.previous_filename||''));
const dispatch=(ref,workflow=ciPath)=>api('actions/workflows/'+workflow+'/dispatches','POST',{ref});
const run=event.workflow_run;
if(run?.head_repository?.full_name===repo && run.conclusion==='failure' && [ciName,'CD · Public Knowledge Base'].includes(run.name)){
 let logs='';try{logs=cli(['run','view',String(run.id),'--repo',repo,'--log-failed'])}catch{}
 const isSidebar=/Invalid config passed to starlight integration/.test(logs)&&/Support for autogenerated sidebar groups was removed/.test(logs);
 const transient=/ETIMEDOUT|EAI_AGAIN|ECONNRESET|runner.*lost communication/i.test(logs)&&!/AssertionError|TypeError|Invalid config received|Invalid config passed/.test(logs);
 const key='run-'+run.id;
 incident(key,'[CI Incident] '+(isSidebar?'Starlight legacy sidebar':transient?'Transient infrastructure failure':'Build or deployment failure')+' · '+run.head_sha.slice(0,12),'Evidence: '+run.html_url+'\n\nSHA: '+run.head_sha+'\n\nClassification: '+(isSidebar?'Known schema migration; https://starlight.astro.build/guides/sidebar/':transient?'Transient candidate; up to 3 total attempts.':'Unknown; research failed job and official docs. Do not guess.')+'\n\nRequired: root cause, minimal patch, regression and verified SHA.');
 const p=prs.find(p=>trusted(p)&&p.head.sha===run.head_sha);
 if(isSidebar&&p&&!sensitive(p)){
  const current=api('contents/astro.config.mjs?ref='+encodeURIComponent(p.head.sha));
  const old=Buffer.from(current.content,'base64').toString('utf8');
  const next=old.replace(/autogenerate: \{ directory: '([a-z0-9-]+)' \}, collapsed: true/g,"collapsed: true, items: [{ autogenerate: { directory: '$1' } }]");
  if(next!==old && api('git/ref/heads/'+encodeURIComponent(p.head.ref)).object.sha===p.head.sha){
   // Contents API rejects a stale file SHA; no checkout or run of PR code.
   api('contents/astro.config.mjs','PUT',{message:'fix(ci): migrate known Starlight sidebar schema',content:Buffer.from(next).toString('base64'),sha:current.sha,branch:p.head.ref});
   dispatch(p.head.ref);
   console.log('Known schema candidate patched; requires new exact-head CI.');
   process.exit(0);
  }
 }
 if(transient&&Number(run.run_attempt)<3&&(p||run.head_sha===main)){api('actions/runs/'+run.id+'/rerun-failed-jobs','POST');process.exit(0)}
}
// Batch only explicitly verified, closed incident records from owner or Actions bot.
const verified=issues.filter(i=>i.state==='closed'&&['duykhang68','github-actions[bot]'].includes(i.user.login)&&hasMarker(i,'<!-- engineering-incident:v1 -->')&&/<!-- verified-sha: [a-f0-9]{40} -->/.test(i.body||'')).sort((a,b)=>a.number-b.number);
for(let i=0;i+5<=verified.length;i+=5){
 const batch=verified.slice(i,i+5), key='techblog-batch-'+batch.map(x=>x.number).join('-'), marker='<!-- '+key+' -->';
 if(!issues.some(x=>hasMarker(x,marker))){
  const issue=api('issues','POST',{title:'[Tech Blog] Engineering retrospective '+batch.map(x=>'#'+x.number).join(', '),body:marker+'\n\nReview these 5 verified incidents and synthesize reusable lessons, tradeoffs and regression tests. No raw logs or secrets. Candidate article only; publish through PR after editorial checks.\n\n'+batch.map(x=>'- '+x.html_url).join('\n')});
  issues.push(issue);
 }
}
if(!prs.length)returnNothing();
function returnNothing(){console.log('Reconciliation complete');}
const p=prs[0];
if(!p||!trusted(p)||sensitive(p)){console.log('No eligible next PR; sensitive/untrusted/draft changes blocked.');process.exit(0)}
const exact=runs.filter(r=>r.head_sha===p.head.sha&&r.head_repository?.full_name===repo&&['pull_request','workflow_dispatch'].includes(r.event)).sort((a,b)=>b.id-a.id)[0];
const current=api('pulls/'+p.number);
if(current.head.sha!==p.head.sha||current.base.sha!==main||current.draft)process.exit(0);
const comparison=api('compare/'+main+'...'+p.head.sha);
if(comparison.status!=='ahead'){
 if(current.mergeable===true){
  try{api('pulls/'+p.number+'/update-branch','PUT',{expected_head_sha:p.head.sha});console.log('Requested conflict-free update; next reconciliation dispatches exact-head CI.')}catch{console.log('Branch update deferred');}
 }else incident('conflict-'+p.number+'-'+p.head.sha,'[Conflict] PR #'+p.number,'PR: '+p.html_url+'\n\nSHA: '+p.head.sha+'\n\nSemantic conflict requires research and regression test; no automatic ours/theirs.');
 process.exit(0);
}
if(!exact){dispatch(p.head.ref);process.exit(0)}
if(exact.status!=='completed'||exact.conclusion!=='success'||current.mergeable!==true)process.exit(0);
const jobs=api('actions/runs/'+exact.id+'/jobs?per_page=100').jobs;
if(!jobs.some(j=>j.name==='Content and Astro build'&&j.conclusion==='success')||jobs.some(j=>j.conclusion!=='success'))process.exit(0);
let marker;try{const res=await fetch('https://duykhang68.github.io/khoahoctienghan/release-sha.json?v='+main,{signal:AbortSignal.timeout(10000),cache:'no-store'});if(res.ok)marker=await res.json()}catch{}
const releases=api('actions/workflows/release.yml/runs?branch=main&per_page=30').workflow_runs;
if(marker?.sha!==main||!releases.some(r=>r.head_sha===main&&r.conclusion==='success')){console.log('Prior main not production-verified; hold FIFO.');process.exit(0)}
if(api('git/ref/heads/main').object.sha!==main)process.exit(0);
const merged=api('pulls/'+p.number+'/merge','PUT',{sha:p.head.sha,merge_method:'merge'});
if(merged.merged){dispatch('main','release.yml');console.log('Merged and dispatched release '+merged.sha)}
