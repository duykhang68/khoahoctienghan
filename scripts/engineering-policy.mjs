export const releaseName='CD · Public Knowledge Base';
export const checkName='Content and Astro build';
export function classify({run,jobs=[],logs='',main}){
 if(run.conclusion!=='failure')return 'IGNORE';
 if(run.name===releaseName && run.head_sha!==main && jobs.some(j=>j.steps?.some(s=>s.name==='Reject stale release'&&s.conclusion==='failure')))return 'SUPERSEDED';
 if(/Invalid config passed to starlight integration/.test(logs)&&/Support for autogenerated sidebar groups was removed/.test(logs))return 'STARLIGHT_SIDEBAR';
 if(/not allowed to deploy to github-pages due to environment protection rules|deployment was rejected or didn't satisfy other protection rules/i.test(logs))return 'ENVIRONMENT_BLOCKED';
 if(/ETIMEDOUT|EAI_AGAIN|ECONNRESET|runner.*lost communication/i.test(logs)&&!/AssertionError|TypeError|Invalid config (?:received|passed)|environment protection/i.test(logs))return 'TRANSIENT';
 return 'UNKNOWN';
}
export function trustedPR(p,repo){return p.user?.login==='duykhang68'&&p.head?.repo?.full_name===repo&&!p.draft&&/^(p\d+[/-]|fix\/|feat\/|ui\/|ux\/|docs\/|techblog\/|perf\/|content\/)/.test(p.head.ref);}
export function sensitiveFile(path=''){return /^(\.github\/|AGENTS\.md$|engineering\/|scripts\/|tests\/|playwright\.config\.|package(?:-lock)?\.json$|astro\.config\.|src\/content\.config\.)/.test(path);}
export function nativePolicyReady(repo,rules){
 return repo.allow_auto_merge&&repo.allow_squash_merge&&rules.some(r=>r.type==='pull_request'&&r.parameters?.allowed_merge_methods?.includes('squash'))&&rules.some(r=>r.type==='non_fast_forward')&&rules.some(r=>r.type==='required_status_checks'&&r.parameters?.strict_required_status_checks_policy&&r.parameters.required_status_checks?.some(c=>c.context===checkName&&c.integration_id>0));
}
export function latestRun(runs,sha,repo,events,branch){return runs.filter(r=>r.head_sha===sha&&r.head_repository?.full_name===repo&&events.includes(r.event)&&(!branch||r.head_branch===branch)).sort((a,b)=>b.id-a.id)[0];}
export function canRetry(kind,run,current){return kind==='TRANSIENT'&&current&&Number(run.run_attempt)<3;}
export function migrateSidebar(old){return old.replace(/autogenerate: \{ directory: '([a-z0-9-]+)' \}, collapsed: true/g,"collapsed: true, items: [{ autogenerate: { directory: '$1' } }]");}

export function branchSyncDecision(pr,comparison){
 if(!Number.isInteger(comparison?.behind_by)||comparison.behind_by<0)return 'UNKNOWN';
 if(pr.mergeable===false)return 'CONFLICT';
 if(pr.mergeable!==true)return 'UNKNOWN';
 if(comparison.behind_by>0)return 'UPDATE';
 if(comparison.status==='ahead'&&comparison.ahead_by>0)return 'CURRENT';
 return 'NO_CHANGES';
}
export function dependabotSyncEligible(p,repo){
 return p.user?.login==='dependabot[bot]'&&p.head?.repo?.full_name===repo&&p.head.ref.startsWith('dependabot/')&&!p.draft&&Boolean(p.auto_merge);
}
