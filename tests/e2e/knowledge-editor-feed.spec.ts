import {test,expect} from '@playwright/test';
import {readdirSync} from 'node:fs';
import {pageWindow} from '../../src/lib/tech-pagination.mjs';
const root='src/content/docs';
const articlePaths=()=>readdirSync(root,{recursive:true,encoding:'utf8'}).filter(p=>/^[^/]+\/.+\.mdx?$/.test(p)&&!p.endsWith('/index.md')&&!p.endsWith('/index.mdx'));
test('knowledge homepage and topic automatically show actual articles and accessible filters',async({page})=>{
 const expected=articlePaths();
 await page.goto('./');
 const feed=page.locator('[data-knowledge-feed]'),cards=feed.locator('[data-knowledge-article]');
 await expect(feed.getByRole('heading',{name:'Bài viết mới nhất'})).toBeVisible();
 await expect(cards).toHaveCount(expected.length);
 const allRoutes=await cards.locator('h3 a').evaluateAll(nodes=>nodes.map(a=>a.getAttribute('href')?.replace(/^\/khoahoctienghan\//,'').replace(/\/$/,'')));
 expect([...allRoutes].sort()).toEqual(expected.map(p=>p.replace(/\.mdx?$/,'')).sort());
 await feed.getByRole('searchbox',{name:'Tìm bài viết'}).fill('hangul');
 const hangul=cards.filter({has:page.locator('h3 a[href$="/ngon-ngu/hangul/"]')});
 await expect(hangul).toHaveCount(1);
 const searchMatches=await cards.evaluateAll(nodes=>nodes.filter(el=>JSON.parse((el as HTMLElement).dataset.article||'{}').search.includes('hangul')).length);
 await expect(feed.locator('[data-knowledge-article]:visible')).toHaveCount(pageWindow(searchMatches,1).end);
 await feed.getByRole('button',{name:'Đặt lại'}).click();
 await expect(feed.locator('[data-knowledge-article]:visible')).toHaveCount(pageWindow(expected.length,1).end);
 await page.goto('./ngon-ngu/');
 const topic=page.locator('[data-knowledge-feed]');
 await expect(topic.locator('[data-knowledge-article]')).toHaveCount(expected.filter(p=>p.startsWith('ngon-ngu/')).length);
 await topic.getByRole('searchbox',{name:'Tìm bài viết'}).fill('hangul');
 const known=topic.locator('h3 a[href$="/ngon-ngu/hangul/"]');
 await expect(known).toHaveCount(1);
 await page.goto('./ngon-ngu/hangul/');await expect(page.locator('h1')).toContainText('Hangul');
 await page.goto('./am-thuc/');
 const foodCount=expected.filter(p=>p.startsWith('am-thuc/')).length;
 await expect(page.locator('[data-knowledge-feed] [data-knowledge-article]')).toHaveCount(foodCount);
 if(foodCount===0)await expect(page.locator('[data-feed-empty]')).toBeVisible();else await expect(page.locator('[data-feed-empty]')).toBeHidden();
 await page.setViewportSize({width:375,height:812});
 await page.goto('./');await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true);
});
