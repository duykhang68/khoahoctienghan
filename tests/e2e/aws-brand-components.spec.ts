import {test,expect} from '@playwright/test';
test('single-link header, footer destinations and accessible mobile layout',async({page})=>{
 await page.goto('./techblog/');
 const header=page.locator('.engineering-header');
 await expect(header.getByRole('link')).toHaveCount(1);
 await expect(header.getByRole('link')).toHaveText('Engineering Blog');
 await expect(header.getByRole('link')).toHaveAttribute('href',/\/techblog\/$/);
 await expect(page.locator('.utility-band,.blog-channel,.blog-tabs,.blog-edition,.nav-cta,.nav-search')).toHaveCount(0);
 const nav=page.locator('.blog-navigation');
 const menu=nav.locator('.edition-menu');
 await expect(nav.locator('summary')).toHaveCount(1);
 await expect(menu.locator('summary')).toHaveText('Chuyên mục');
 await expect(menu.locator('.edition-panel')).toBeHidden();
 await menu.locator('summary').click();
 await expect(menu.locator('.edition-panel')).toBeVisible();
 await expect(menu.locator('.edition-panel a').first()).toHaveText('Tất cả bài viết');
 const topic=menu.locator('.edition-panel a[href*="?category="]').first();
 await expect(topic).toBeVisible();
 await menu.locator('summary').press('Escape');
 await expect(menu.locator('.edition-panel')).toBeHidden();
 await expect(page.locator('.search-submit')).toHaveCount(0);
 const footer=page.locator('.engineering-footer');
 await expect(footer.locator('section')).toHaveCount(1);
 await expect(footer.getByRole('link')).toHaveCount(2);
 await expect(footer.getByRole('heading',{name:'Khám phá',exact:true})).toHaveCount(0);
 await expect(footer.getByRole('heading',{name:'Tài nguyên',exact:true})).toHaveCount(0);
 await expect(footer.locator('.footer-brand')).toHaveText('Engineering Blog');
 const signature=footer.locator('.footer-bottom > div');
 await expect(signature).toHaveText('Tri thức Hàn Quốc · Engineering');
 await expect(signature).toHaveCSS('text-align','right');
 await expect(signature).toHaveCSS('font-weight','700');
 await expect(signature).toHaveCSS('color','rgb(175, 175, 175)');
 const kbHref=(await footer.locator('.footer-cta').getAttribute('href'))!;
 expect(kbHref).toMatch(/\/khoahoctienghan\/$/);
 await expect(footer.locator('a[href="'+kbHref+'"]')).toHaveCount(1);
 await expect(page.locator('a[href="'+kbHref+'"]')).toHaveCount(1);
 await expect(page.locator('.blog-breadcrumb')).toHaveText('Engineering Blog');
 await expect(page.locator('#categories')).toHaveCount(0);
 const first=page.locator('[data-tech-post]').first();
 const title=(await first.locator('h3').innerText()).trim();
 await first.locator('h3 a').click();
 await expect(header.getByRole('link')).toHaveCount(1);
 await expect(header.getByRole('link')).toHaveText('Engineering Blog');
 await expect(page.locator('.blog-breadcrumb a')).toHaveCount(1);
 await expect(page.locator('.blog-breadcrumb a')).toHaveAttribute('href',/\/techblog\/$/);
 await expect(page.locator('a[href="'+kbHref+'"]')).toHaveCount(1);
 await expect(page.locator('.current-crumb')).toHaveText(title);
 await expect(page.locator('.article-heading h1')).toHaveText(title);
 await expect(page.locator('.research-meta .post-meta')).toBeVisible();
 await expect(page.locator('.article-body .article-lead')).toHaveCSS('text-align','justify');
 await expect(page.locator('.research-meta')).toBeVisible();
 await expect(page.locator('.tech-sidebar')).toHaveCount(0);
 await expect(page.locator('.footer-cta')).toBeVisible();
 await expect(footer.locator('section')).toHaveCount(1);
 await expect(footer.getByRole('link')).toHaveCount(2);
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2)).toBe(true);
 await page.setViewportSize({width:375,height:812});
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2)).toBe(true);
 await expect(page.locator('.blog-breadcrumb a').last()).toHaveText('Engineering Blog');
 await menu.locator('summary').click();
 await expect(topic).toBeVisible();
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2)).toBe(true);
 const href=await topic.getAttribute('href');
 await topic.click();
 await expect(page).toHaveURL(new URL(href!,page.url()).href);
 await expect(page.locator('#feed-heading')).toContainText('Chuyên mục:');
});
